/* 02_esquema.sql — Tablas y vistas de BD_CURSO_HFC (ADR-0002). Idempotente: se puede correr en cada deploy.
   Lo corre sql/semilla.py con el login curso_hfc_carga. El permiso de lectura de la API está en 01_crear_bd.sql.

   Modelo: los datos llegan ya agregados, igual que en producción (las cargas ETL de Claro alimentan
   KPIS_PENALIDADES_HFC y la trazabilidad). La demo guarda directamente ese grano:
     TBL_KPI_FRANJA     día × franja de 30 min (fuente de Diario e Intervalos)
     TBL_GESTION_ASESOR día × asesor            (fuente de Supervisores y Asesores)
     TBL_NOMINA         un registro por asesor  (supervisor, coordinador, condición laboral…)
     TBL_USUARIOS       quién entra al panel y con qué perfil */
IF OBJECT_ID('dbo.TBL_KPI_FRANJA') IS NULL
CREATE TABLE dbo.TBL_KPI_FRANJA (
    FECHA            DATE         NOT NULL,
    FRANJA_GTR       CHAR(5)      NOT NULL,
    LLAM_RECIBIDAS   INT NOT NULL, CANT_ATENDIDA INT NOT NULL, CANT_ABANDONADA INT NOT NULL,
    ATENDIDA_UMBR    INT NOT NULL, MENOR_90SEG   INT NOT NULL, CORTE_AGENTE    INT NOT NULL,
    TMG_TOTAL_SEG    INT NOT NULL, TMG_PROMSEG   INT NOT NULL, TMP_HABLADO     INT NOT NULL, TMP_PROD INT NOT NULL,
    TRANS_ENCU       INT NOT NULL, ENCU_CAL      INT NOT NULL,
    CANT_PROMOTOR    INT NOT NULL, CANT_DETRACTOR INT NOT NULL, CANT_PASIVO   INT NOT NULL,
    TRAF_DIM         INT NOT NULL, TMG_DIM DECIMAL(9,2) NOT NULL, AGENT_DIM DECIMAL(9,2) NOT NULL, HORAS_DIM DECIMAL(9,2) NOT NULL,
    AGENTE_BR        DECIMAL(9,2) NOT NULL, AGENTE_NETO_IDLE DECIMAL(9,2) NOT NULL, AGENTE_NETO DECIMAL(9,2) NOT NULL,
    TRANS_VICIO      INT NOT NULL, TRANS_IVR_123 INT NOT NULL, TRANS_OTROS_BPO INT NOT NULL, TRANS_OTROS_GEA INT NOT NULL,
    CONSTRAINT PK_KPI_FRANJA PRIMARY KEY (FECHA, FRANJA_GTR),
    CONSTRAINT CK_KPI_ATENDIDAS CHECK (CANT_ATENDIDA + CANT_ABANDONADA = LLAM_RECIBIDAS)
);
GO
IF OBJECT_ID('dbo.TBL_NOMINA') IS NULL
CREATE TABLE dbo.TBL_NOMINA (
    USUARIO        VARCHAR(10)  NOT NULL CONSTRAINT PK_NOMINA PRIMARY KEY,
    NOMBRE_ASESOR  NVARCHAR(80) NOT NULL,
    SUPERVISOR     NVARCHAR(80) NOT NULL,
    COORDINADOR    NVARCHAR(80) NOT NULL,
    CONDICION_LAB  VARCHAR(20)  NOT NULL,
    ESTADO_OP      VARCHAR(20)  NOT NULL,   -- Modalidad: PRESENCIAL / REMOTO
    ESTADO         VARCHAR(20)  NOT NULL,   -- ACTIVO / CESADO
    CONTRATO       VARCHAR(20)  NOT NULL    -- OPERACIONES / OJT
);
GO
IF OBJECT_ID('dbo.TBL_GESTION_ASESOR') IS NULL
CREATE TABLE dbo.TBL_GESTION_ASESOR (
    FECHA          DATE        NOT NULL,
    USUARIO        VARCHAR(10) NOT NULL CONSTRAINT FK_GESTION_NOMINA REFERENCES dbo.TBL_NOMINA(USUARIO),
    CANT_ATENDIDA  INT NOT NULL, CORTE_AGENTE INT NOT NULL, CANT_HOLD INT NOT NULL, CORTE_CLIENTE INT NOT NULL,
    TMG_TOTAL_SEG  INT NOT NULL, TPM_TOTAL INT NOT NULL, TMP_HABLADO INT NOT NULL, TMP_DISPO INT NOT NULL,
    TMP_PROD       INT NOT NULL, TMP_TIPIF INT NOT NULL,
    CANT_PROMOTOR  INT NOT NULL, CANT_DETRACTOR INT NOT NULL, CANT_PASIVO INT NOT NULL,
    TRANS_ENCU     INT NOT NULL, ENCU_CAL INT NOT NULL,
    TRANS_VICIO    INT NOT NULL, TRANS_IVR_123 INT NOT NULL, TRANS_OTROS_BPO INT NOT NULL, TRANS_OTROS_GEA INT NOT NULL,
    CONSTRAINT PK_GESTION_ASESOR PRIMARY KEY (FECHA, USUARIO)
);
GO
IF OBJECT_ID('dbo.TBL_USUARIOS') IS NULL
CREATE TABLE dbo.TBL_USUARIOS (
    USUARIO_E   VARCHAR(30)  NOT NULL CONSTRAINT PK_USUARIOS PRIMARY KEY,
    NOMBRE      NVARCHAR(80) NOT NULL,
    PERFIL      VARCHAR(20)  NOT NULL CONSTRAINT CK_USUARIOS_PERFIL CHECK (PERFIL IN ('ADMINISTRADOR','SUPERVISOR','CLIENTE CLARO')),
    HASH_CLAVE  VARCHAR(200) NOT NULL,
    ACTIVO      BIT          NOT NULL CONSTRAINT DF_USUARIOS_ACTIVO DEFAULT 1
);
GO
/* Columnas derivadas comunes: PERIODO AAAAMM, semana del mes y fecha legible en español. */
CREATE OR ALTER VIEW dbo.VW_DIARIO AS
SELECT
    CONVERT(CHAR(6), K.FECHA, 112) AS PERIODO,
    CONVERT(CHAR(10), K.FECHA, 23) AS FECHA,
    CONCAT(RIGHT('0' + CAST(DAY(K.FECHA) AS VARCHAR(2)), 2), '-', FORMAT(K.FECHA, 'MMM', 'es-ES'),
           ' (', FORMAT(K.FECHA, 'ddd', 'es-ES'), ')') AS FECHA_VISUAL,
    'SEM-' + CAST(((DAY(K.FECHA) - 1) / 7) + 1 AS VARCHAR(2)) AS SEMANA,
    K.FRANJA_GTR, K.LLAM_RECIBIDAS, K.CANT_ATENDIDA, K.CANT_ABANDONADA, K.ATENDIDA_UMBR, K.MENOR_90SEG,
    K.CORTE_AGENTE, K.TMG_TOTAL_SEG, K.TMG_PROMSEG, K.TMP_HABLADO, K.TMP_PROD, K.TRANS_ENCU, K.ENCU_CAL,
    K.CANT_PROMOTOR, K.CANT_DETRACTOR, K.CANT_PASIVO, K.TRAF_DIM, K.TMG_DIM, K.AGENT_DIM, K.HORAS_DIM,
    K.AGENTE_BR, K.AGENTE_NETO_IDLE, K.AGENTE_NETO,
    K.TRANS_VICIO, K.TRANS_IVR_123, K.TRANS_OTROS_BPO, K.TRANS_OTROS_GEA
FROM dbo.TBL_KPI_FRANJA K;
GO
CREATE OR ALTER VIEW dbo.VW_SUPERVISORES AS
SELECT
    CONVERT(CHAR(6), G.FECHA, 112) AS PERIODO,
    CONVERT(CHAR(10), G.FECHA, 23) AS FECHA,
    CONCAT(RIGHT('0' + CAST(DAY(G.FECHA) AS VARCHAR(2)), 2), '-', FORMAT(G.FECHA, 'MMM', 'es-ES'),
           ' (', FORMAT(G.FECHA, 'ddd', 'es-ES'), ')') AS FECHA_VISUAL,
    'SEM-' + CAST(((DAY(G.FECHA) - 1) / 7) + 1 AS VARCHAR(2)) AS SEMANA,
    G.USUARIO, N.NOMBRE_ASESOR, N.SUPERVISOR, N.CONDICION_LAB, N.COORDINADOR, N.ESTADO_OP, N.ESTADO, N.CONTRATO,
    G.CANT_ATENDIDA, G.CORTE_AGENTE, G.CANT_HOLD, G.TMG_TOTAL_SEG,
    G.TPM_TOTAL, G.TMP_HABLADO, G.TMP_DISPO, G.TMP_PROD, G.TMP_TIPIF,
    G.CANT_PROMOTOR, G.CANT_DETRACTOR, G.CANT_PASIVO,
    G.TRANS_VICIO, G.TRANS_IVR_123, G.TRANS_OTROS_BPO, G.TRANS_OTROS_GEA,
    G.CORTE_CLIENTE, G.TRANS_ENCU, G.ENCU_CAL
FROM dbo.TBL_GESTION_ASESOR G
JOIN dbo.TBL_NOMINA N ON N.USUARIO = G.USUARIO;
GO
